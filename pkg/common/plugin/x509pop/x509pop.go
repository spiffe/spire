var DefaultAgentPathTemplateSVID = agentpathtemplate.MustParse("/{{ .PluginName }}/{{ .SVIDPathTrimmed }}")

// TemplateData is hydrated into the templates evaluated by this plugin. The
// same data is used for every template so that they all have access to the same
// certificate details.
type TemplateData struct {
	*x509.Certificate
	SerialNumberHex string
	Fingerprint     string
	PluginName      string
	TrustDomain     string
	SVIDPathTrimmed string
	URISanSelectors map[string]string
}

// NewTemplateData returns the data to hydrate templates with for the given
// certificate.
func NewTemplateData(td spiffeid.TrustDomain, cert *x509.Certificate, svidPathTrimmed string, sanSelectors map[string]string) TemplateData {
	return TemplateData{
		TrustDomain:     td.Name(),
		Certificate:     cert,
		PluginName:      PluginName,
		SerialNumberHex: SerialNumberHex(cert.SerialNumber),
		Fingerprint:     Fingerprint(cert),
		SVIDPathTrimmed: svidPathTrimmed,
		URISanSelectors: sanSelectors,
	}
}

type AttestationData struct {
	// DER encoded x509 certificate chain leading back to the trusted root. The
	// leaf certificate comes first.
	Certificates [][]byte `json:"certificates"`
}

type RSASignatureChallenge struct {
	// Nonce is the nonce generated by the challenger.
	Nonce []byte `json:"nonce"`
}

type RSASignatureResponse struct {
	// Nonce is the nonce generated by the responder.
	Nonce []byte `json:"nonce"`

	// Signature is the RSA signature of the combined challenger and responder
	// nonces.
	Signature []byte `json:"signature"`
}

type ECDSASignatureChallenge struct {
	// Nonce is the nonce generated by the challenger.
	Nonce []byte `json:"nonce"`
}

type ECDSASignatureResponse struct {
	// Nonce is the nonce generated by the responder.
	Nonce []byte `json:"nonce"`

	// R value of the ECDSA signature of the combined challenger and responder
	// nonces.
	R []byte `json:"r"`

	// S value of the ECDSA signature of the combined challenger and responder
	// nonces.
	S []byte `json:"s"`
}

type Challenge struct {
	RSASignature   *RSASignatureChallenge   `json:"rsa_signature"`
	ECDSASignature *ECDSASignatureChallenge `json:"ecdsa_signature"`

	// Hash identifies the hash algorithm used to digest the combined nonces
	// and to sign them. It is omitted for SHA-256 so that challenges remain
	// identical to those produced before hash selection was introduced.
	// An empty value means SHA-256.
	Hash string `json:"hash,omitempty"`
}

type Response struct {
	RSASignature   *RSASignatureResponse   `json:"rsa_signature"`
	ECDSASignature *ECDSASignatureResponse `json:"ecdsa_signature"`
}

// GenerateChallenge generates a challenge for the given certificate that
// requires the response to be computed with the given hash algorithm.
func GenerateChallenge(cert *x509.Certificate, hashAlg string) (*Challenge, error) {
	hash, err := ParseHashAlgorithm(hashAlg)
	if err != nil {
		return nil, err
	}
	// SHA-256 is left implicit to keep the wire format unchanged for agents
	// that predate hash selection.
	if hash == crypto.SHA256 {
		hashAlg = ""
	}

	// ensure that the public key is intended to be used for digital signatures
	if (cert.KeyUsage & x509.KeyUsageDigitalSignature) == 0 {
		return nil, errors.New("certificate not intended for digital signature use")
	}

	switch publicKey := cert.PublicKey.(type) {
	case *rsa.PublicKey:
		challenge, err := GenerateRSASignatureChallenge()
		if err != nil {
			return nil, err
		}
		return &Challenge{
			RSASignature: challenge,
			Hash:         hashAlg,
		}, nil
	case *ecdsa.PublicKey:
		challenge, err := GenerateECDSASignatureChallenge()
		if err != nil {
			return nil, err
		}
		return &Challenge{
			ECDSASignature: challenge,
			Hash:           hashAlg,
		}, nil
	default:
		return nil, fmt.Errorf("unsupported public key type %T", publicKey)
	}
}

func CalculateResponse(privateKey any, challenge *Challenge) (*Response, error) {
	hash, err := ParseHashAlgorithm(challenge.Hash)
	if err != nil {
		return nil, err
	}

	switch privateKey := privateKey.(type) {
	case *rsa.PrivateKey:
		rsaChallenge := challenge.RSASignature
		if rsaChallenge == nil {
			return nil, errors.New("expecting RSA challenge")
		}
		response, err := CalculateRSASignatureResponse(privateKey, rsaChallenge, hash)
		if err != nil {
			return nil, err
		}
		return &Response{
			RSASignature: response,
		}, nil
	case *ecdsa.PrivateKey:
		if challenge.ECDSASignature == nil {
			return nil, errors.New("expecting ECDSA challenge")
		}
		response, err := CalculateECDSASignatureResponse(privateKey, challenge.ECDSASignature, hash)
		if err != nil {
			return nil, err
		}
		return &Response{
			ECDSASignature: response,
		}, nil
	default:
		return nil, fmt.Errorf("unsupported private key type %T", privateKey)
	}
}

// VerifyChallengeResponse verifies the response against the challenge. The
// hash algorithm is always taken from the challenge, which is generated and
// retained by the verifier, so a response cannot select a different algorithm.
func VerifyChallengeResponse(publicKey any, challenge *Challenge, response *Response) error {
	hash, err := ParseHashAlgorithm(challenge.Hash)
	if err != nil {
		return err
	}

	switch publicKey := publicKey.(type) {
	case *rsa.PublicKey:
		if challenge.RSASignature == nil {
			return errors.New("expecting RSA challenge")
		}
		if response.RSASignature == nil {
			return errors.New("expecting RSA response")
		}
		return VerifyRSASignatureResponse(publicKey, challenge.RSASignature, response.RSASignature, hash)
	case *ecdsa.PublicKey:
		if challenge.ECDSASignature == nil {
			return errors.New("expecting ECDSA challenge")
		}
		if response.ECDSASignature == nil {
			return errors.New("expecting ECDSA response")
		}
		return VerifyECDSASignatureResponse(publicKey, challenge.ECDSASignature, response.ECDSASignature, hash)
	default:
		return fmt.Errorf("unsupported private key type %T", publicKey)
	}
}

func GenerateRSASignatureChallenge() (*RSASignatureChallenge, error) {
	nonce, err := generateNonce()
	if err != nil {
		return nil, err
	}

	return &RSASignatureChallenge{
		Nonce: nonce,
	}, nil
}

// CalculateRSASignatureResponse calculates an RSA-PSS response using the given hash.
func CalculateRSASignatureResponse(privateKey *rsa.PrivateKey, challenge *RSASignatureChallenge, hash crypto.Hash) (*RSASignatureResponse, error) {
	nonce, err := generateNonce()
	if err != nil {
		return nil, err
	}

	combined, err := combineNoncesWithHash(challenge.Nonce, nonce, hash)
	if err != nil {
		return nil, err
	}

	signature, err := rsa.SignPSS(rand.Reader, privateKey, hash, combined, nil)
	if err != nil {
		return nil, err
	}

	return &RSASignatureResponse{
		Signature: signature,
		Nonce:     nonce,
	}, nil
}

// VerifyRSASignatureResponse verifies an RSA-PSS response using the given hash.
func VerifyRSASignatureResponse(publicKey *rsa.PublicKey, challenge *RSASignatureChallenge, response *RSASignatureResponse, hash crypto.Hash) error {
	combined, err := combineNoncesWithHash(challenge.Nonce, response.Nonce, hash)
	if err != nil {
		return err
	}

	if err := rsa.VerifyPSS(publicKey, hash, combined, response.Signature, nil); err != nil {
		return errors.New("RSA signature verify failed")
	}
	return nil
}

func GenerateECDSASignatureChallenge() (*ECDSASignatureChallenge, error) {
	nonce, err := generateNonce()
	if err != nil {
		return nil, err
	}

	return &ECDSASignatureChallenge{
		Nonce: nonce,
	}, nil
}

// CalculateECDSASignatureResponse calculates an ECDSA response using the given hash.
func CalculateECDSASignatureResponse(privateKey *ecdsa.PrivateKey, challenge *ECDSASignatureChallenge, hash crypto.Hash) (*ECDSASignatureResponse, error) {
	nonce, err := generateNonce()
	if err != nil {
		return nil, err
	}

	combined, err := combineNoncesWithHash(challenge.Nonce, nonce, hash)
	if err != nil {
		return nil, err
	}

	r, s, err := ecdsa.Sign(rand.Reader, privateKey, combined)
	if err != nil {
		return nil, err
	}

	return &ECDSASignatureResponse{
		Nonce: nonce,
		R:     r.Bytes(),
		S:     s.Bytes(),
	}, nil
}

// VerifyECDSASignatureResponse verifies an ECDSA response using the given hash.
func VerifyECDSASignatureResponse(publicKey *ecdsa.PublicKey, challenge *ECDSASignatureChallenge, response *ECDSASignatureResponse, hash crypto.Hash) error {
	combined, err := combineNoncesWithHash(challenge.Nonce, response.Nonce, hash)
	if err != nil {
		return err
	}

	r := new(big.Int)
	r.SetBytes(response.R)
	s := new(big.Int)
	s.SetBytes(response.S)
	if !ecdsa.Verify(publicKey, combined, r, s) {
		return errors.New("ECDSA signature verify failed")
	}
	return nil
}

func Fingerprint(cert *x509.Certificate) string {
	sum := sha1.Sum(cert.Raw) //nolint: gosec // SHA1 use is according to specification
	return hex.EncodeToString(sum[:])
}

// MakeAgentID creates an agent ID from X.509 certificate data.
func MakeAgentID(td spiffeid.TrustDomain, agentPathTemplate *agentpathtemplate.Template, cert *x509.Certificate, svidPathTrimmed string, sanSelectors map[string]string) (spiffeid.ID, error) {
	agentPath, err := agentPathTemplate.Execute(NewTemplateData(td, cert, svidPathTrimmed, sanSelectors))
	if err != nil {
		return spiffeid.ID{}, err
	}

	return idutil.AgentID(td, agentPath)
}

// SerialNumberHex returns a certificate serial number represented as lowercase hexadecimal with an even number of characters
func SerialNumberHex(serialNumber *big.Int) string {
	serialHex := fmt.Sprintf("%x", serialNumber)
	if len(serialHex)%2 == 1 {
		// Append leading 0 in cases where hexadecimal representation is odd number of characters
		// in order to be more consistent with other tooling that displays certificate serial numbers.
		serialHex = "0" + serialHex
	}

	return serialHex
}

func generateNonce() ([]byte, error) {
	b := make([]byte, nonceLen)
	if _, err := rand.Read(b); err != nil {
		return nil, err
	}
	return b, nil
}

func combineNoncesWithHash(challenge, response []byte, hashAlg crypto.Hash) ([]byte, error) {
	if len(challenge) != nonceLen {
		return nil, errors.New("invalid challenge nonce")
	}
	if len(response) != nonceLen {
		return nil, errors.New("invalid response nonce")
	}
	var h hash.Hash
	switch hashAlg {
	case crypto.SHA256:
		h = sha256.New()
	case crypto.SHA384:
		h = sha512.New384()
	default:
		return nil, fmt.Errorf("unsupported hash algorithm %v", hashAlg)
	}
	// Writing to a digest never fails.
	_, _ = h.Write(challenge)
	_, _ = h.Write(response)
	return h.Sum(nil), nil
}
